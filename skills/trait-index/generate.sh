#!/usr/bin/env bash

# Writes traits/README.md from the frontmatter of every trait file in the current
# repository, creating traits/ and installing SPEC.md on first use.

set -euo pipefail

if (( $# > 1 )) || [[ $# == 1 && $1 != --check-spec ]]; then
    printf 'Usage: %s [--check-spec]\n' "${0##*/}" >&2
    exit 2
fi

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
TRAITS="$ROOT/traits"
INDEX="$TRAITS/README.md"
SPEC="$TRAITS/SPEC.md"
BUNDLED_SPEC="$SKILL_DIR/SPEC.md"

if [[ -L "$TRAITS" || ( -e "$TRAITS" && ! -d "$TRAITS" ) ]]; then
    printf 'Expected a directory inside the project at %s\n' "$TRAITS" >&2
    exit 1
fi

format_version() {
    awk '
        { sub(/\r$/, "") }
        /^[[:space:]]*<!--[[:space:]]*traits-format/ {
            if (version != "" || $0 !~ /^<!-- traits-format: [1-9][0-9]* -->$/) {
                invalid = 1
                exit
            }
            version = $3
        }
        END {
            if (invalid) exit 1
            print version
        }
    ' "$1"
}

if ! bundled_version="$(format_version "$BUNDLED_SPEC")" || [[ -z "$bundled_version" ]]; then
    printf 'Expected one traits-format marker in %s\n' "$BUNDLED_SPEC" >&2
    exit 1
fi

check_project_format() {
    local version

    if [[ -L "$SPEC" || ( -e "$SPEC" && ! -f "$SPEC" ) ]]; then
        printf 'Expected a regular file at %s\n' "$SPEC" >&2
        return 1
    fi
    [[ -f "$SPEC" ]] || return 0

    if ! version="$(format_version "$SPEC")"; then
        printf 'Malformed or duplicate traits-format marker in %s\n' "$SPEC" >&2
        return 1
    fi
    version="${version:-1}"
    if [[ "$version" != "$bundled_version" ]]; then
        printf 'Project trait format %s differs from bundled format %s. Use a matching Traits release or migrate the project traits.\n' \
            "$version" "$bundled_version" >&2
        return 1
    fi
}

check_project_format
if [[ "${1:-}" == --check-spec ]]; then
    printf 'Project is compatible with trait format %s\n' "$bundled_version"
    exit 0
fi

if [[ -L "$INDEX" || ( -e "$INDEX" && ! -f "$INDEX" ) ]]; then
    printf 'Expected a regular file at %s\n' "$INDEX" >&2
    exit 1
fi
mkdir -p "$TRAITS"

staging="$(mktemp -d "$TRAITS/.trait-index.XXXXXXXX")"
trap 'rm -f "$staging/README.md" "$staging/SPEC.md"; rmdir "$staging"' EXIT

if [[ ! -f "$SPEC" ]]; then
    cp "$BUNDLED_SPEC" "$staging/SPEC.md"
    if ln -n "$staging/SPEC.md" "$SPEC" 2>/dev/null; then
        echo "installed traits/SPEC.md"
    elif [[ ! -f "$SPEC" ]]; then
        printf 'Could not install %s\n' "$SPEC" >&2
        exit 1
    fi
fi
check_project_format

# The value of a one-line frontmatter field, without its surrounding quotes.
field() {
    awk -v key="$1" '
        { sub(/\r$/, "") }
        NR == 1 {
            if ($0 != "---") exit
            next
        }
        /^---$/ {
            print value
            exit
        }
        !found && index($0, key ": ") == 1 {
            value = substr($0, length(key) + 3)
            gsub(/^"|"$/, "", value)
            found = 1
        }
    ' "$2"
}

failed=0
count=0
rows=""

for file in "$TRAITS"/*.md; do
    [[ -e "$file" ]] || continue
    slug="$(basename "$file" .md)"

    # Trait slugs are lowercase; README.md and SPEC.md are not traits.
    if [[ "$slug" == "README" || "$slug" == "SPEC" ]]; then
        continue
    fi

    description="$(field description "$file")"
    when="$(field when "$file")"

    if [[ -z "$description" || -z "$when" ]]; then
        echo "traits/$slug.md: fenced frontmatter must contain description and when" >&2
        failed=1
        continue
    fi

    rows+="| [$slug]($slug.md) | ${description//|/\\|} | ${when//|/\\|} |"$'\n'
    count=$((count + 1))
done

if [[ "$failed" -ne 0 ]]; then
    exit 1
fi

if [[ -f "$INDEX" ]]; then
    cp -p "$INDEX" "$staging/README.md"
fi

{
    echo "# Traits"
    echo
    echo "Generated by the trait-index skill; do not edit. The format of a trait file is"
    echo "in [SPEC.md](SPEC.md)."
    echo
    echo "| Trait | What the code does | When it matters |"
    echo "|---|---|---|"
    printf '%s' "$rows"
} > "$staging/README.md"
mv -f "$staging/README.md" "$INDEX"

echo "wrote traits/README.md ($count traits)"
